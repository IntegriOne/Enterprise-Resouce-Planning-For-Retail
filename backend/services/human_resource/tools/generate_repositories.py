#!/usr/bin/env python3
# Generator model/port/repository dari baseline SQL HRM; tanpa perubahan database.
from pathlib import Path
import re,subprocess
root=Path(__file__).resolve().parents[1]
sql=(root/'db/migrations/000001_hrm.up.sql').read_text()
readme=(root/'README.md').read_text()
module='github.com/integrione/erp-retail/backend/services/human_resource'
def camel(s):
 return ''.join({'id':'ID','iam':'IAM','fte':'FTE','uom':'UOM','url':'URL','kpi':'KPI'}.get(p,p.title()) for p in s.split('_'))
def singular(s):
 return {'families':'family','policies':'policy','entries':'entry','competencies':'competency'}.get(s,s[:-1] if s.endswith('s') else s)
def name(t):
 p=t.removeprefix('hr_').split('_');p[-1]=singular(p[-1]);return camel('_'.join(p))
owner={}
for domain,tables in re.findall(r'^\| `([a-z]+)` \| (.+) \|$',readme,re.M):
 for t in re.findall(r'`(hr_\w+)`',tables):owner[t]=domain
owner.update(hr_inbox_events='inbox',hr_outbox_events='outbox')
enums={n:camel(n.removeprefix('hr_').removesuffix('_enum')) for n in re.findall(r'CREATE TYPE "(\w+)" AS ENUM',sql)}
def gotype(typ):
 if typ in enums:return enums[typ]
 if typ=='uuid' or typ.startswith(('varchar','char')) or typ=='text':return 'string'
 if typ=='boolean':return 'bool'
 if typ=='smallint':return 'int16'
 if typ=='integer':return 'int32'
 if typ.lower()=='bigint' or typ=='BIGINT':return 'int64'
 if typ in ('date','timestamptz'):return 'time.Time'
 if typ.startswith('numeric'):return 'Decimal'
 if typ=='jsonb':return 'JSON'
 if typ=='bytea':return '[]byte'
 raise ValueError(typ)
tables=[]
for table,body in re.findall(r'CREATE TABLE "([^"]+)" \((.*?)\n\);',sql,re.S):
 cols=[]
 for col,decl in re.findall(r'^  "([^"]+)" ([^\n]+)',body,re.M):
  typ=re.match(r'\w+(?:\([^)]*\))?',decl)[0]
  pk='PRIMARY KEY' in decl or (table=='hr_learning_course_competencies' and col in ('course_id','competency_id'))
  nullable=not pk and 'NOT NULL' not in decl
  gt=gotype(typ)
  if nullable and gt not in ('JSON','[]byte'):gt='*'+gt
  cols.append(dict(column=col,sql_type=typ,type=gt,field=camel(col),pk=pk,serial='IDENTITY' in decl))
 tables.append(dict(table=table,name=name(table),domain=owner[table],columns=cols))
assert len(tables)==len(owner), 'Pemetaan tabel README tidak lengkap'
dbml=(root/'db/schema/human_resource_management.dbml').read_text()
dbml_tables={n:body for n,body in re.findall(r'^Table (\w+) \{(.*?)^\}',dbml,re.M|re.S)}
assert set(dbml_tables)=={t['table'] for t in tables}, 'Baseline SQL berbeda dari DBML'
for t in tables:
 dbml_columns={c for c,typ in re.findall(r'^  (\w+) (\w+(?:\([^)]*\))?)',dbml_tables[t['table']],re.M) if c not in ('indexes','checks','Note')}
 assert dbml_columns=={c['column'] for c in t['columns']}, 'Kolom berbeda: '+t['table']
manifest=[]
def write(p,s):
 p=root/p;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(s);manifest.append(str(p))
header='// Code generated by tools/generate_repositories.py; DO NOT EDIT.\n// Sumber model adalah baseline SQL HRM; aturan bisnis tetap milik service.\n'
write(Path('domain/entity/enums.go'),header+'package entity\n\n'+ '\n'.join('type '+enums[n]+' string\nconst (\n'+''.join(f' {enums[n]}{camel(v)} {enums[n]} = "{v}"\n' for v in re.findall(r"'([^']+)'",values))+')\n' for n,values in re.findall(r'CREATE TYPE "(\w+)" AS ENUM \((.*?)\);',sql,re.S)))
bydomain={}
for t in tables:bydomain.setdefault(t['domain'],[]).append(t)
for dom,ts in bydomain.items():
 use_time=any('time.Time' in c['type'] for t in ts for c in t['columns'])
 out=header+'package entity\n'+ ('\nimport "time"\n' if use_time else '')
 for t in ts:
  out+=f'\n// {t["name"]} memetakan baris {t["table"]}.\ntype {t["name"]} struct {{\n'
  for c in t['columns']:
   tag='column:'+c['column']+';type:'+c['sql_type'].lower()
   if c['pk']:tag+=';primaryKey;autoIncrement:'+str(c['serial']).lower()
   if c['column'] in ('created_at','updated_at'):tag+=';autoCreateTime:false;autoUpdateTime:false'
   out+=f' {c["field"]} {c["type"]} `gorm:"{tag}" json:"{c["column"]}"`\n'
  out+='}\n'+f'\n// TableName menetapkan tabel HRM secara eksplisit.\nfunc ({t["name"]}) TableName() string {{ return "{t["table"]}" }}\n'
 write(Path('domain/entity')/(dom+'.go'),out)
 for t in ts:
  n=t['name'];cols=t['columns'];pks=[c for c in cols if c['pk']]
  key='string' if len(pks)==1 and pks[0]['type']=='string' else 'int64' if len(pks)==1 else 'entity.'+n+'Key'
  t['key']=key
  if len(pks)>1:
   with (root/'domain/entity'/f'{dom}.go').open('a') as f:f.write(f'\n// {n}Key menyimpan seluruh bagian primary key.\ntype {n}Key struct {{\n'+''.join(f' {c["field"]} {c["type"]}\n' for c in pks)+'}\n')
  filters=[c for c in cols if not c['pk'] and (c['sql_type']=='uuid' or c['column'].endswith(('_code','_number','_status','_type')) or c['column'] in ('status','idempotency_key','source_event_id','source_management','aggregate_version') or (c['sql_type'].lower()=='bigint' and c['column'].endswith('_id')))]
  # Kedua bagian composite key juga mempunyai pencarian berhalaman.
  if len(pks)>1:filters=pks+filters
  t['filters']=filters
  ct=lambda typ: 'entity.'+typ if typ in enums.values() or typ in ('Decimal','JSON') else '*entity.'+typ[1:] if typ.startswith('*') and typ[1:] in enums.values() else typ
  interface=f'\n// {n}Repository adalah port persistensi {t["table"]}.\ntype {n}Repository interface {{\n Repository[entity.{n}, {key}]\n'
  repo=header+f'package {dom}\n\nimport (\n "context"\n\n "gorm.io/gorm"\n\n "{module}/domain/entity"\n domainrepo "{module}/domain/repository"\n "{module}/repository/pgstore"\n)\n\n'
  repo+=f'// {n}Repository menyediakan kueri bertipe untuk {t["table"]}.\ntype {n}Repository struct {{ *pgstore.Repository[entity.{n}, {key}] }}\n\nvar _ domainrepo.{n}Repository = (*{n}Repository)(nil)\n\n'
  keyvals=', '.join('key' if len(pks)==1 else 'key.'+c['field'] for c in pks)
  repo+=f'// New{n}Repository memvalidasi koneksi dan menyiapkan repository.\nfunc New{n}Repository(db *gorm.DB) (*{n}Repository, error) {{\n base, err := pgstore.New[entity.{n}, {key}](db, func(key {key}) []any {{ return []any{{{keyvals}}} }})\n if err != nil {{ return nil, err }}\n return &{n}Repository{{Repository:base}}, nil\n}}\n'
  for c in filters:
   typ=ct(c['type']);meth='FindBy'+c['field']
   interface+=f' {meth}(ctx context.Context, value {typ}, limit, offset int) ([]entity.{n}, error)\n'
   repo+=f'\n// {meth} mencari kecocokan {c["column"]} dengan paginasi dan urutan primary key.\nfunc (r *{n}Repository) {meth}(ctx context.Context, value {typ}, limit, offset int) ([]entity.{n}, error) {{\n return r.SelectBy(ctx, "{c["column"]}", value, limit, offset)\n}}\n'
  t['interface']=interface+'}\n'
  write(Path('repository')/dom/(t['table'].removeprefix('hr_')+'_repository.go'),repo)
 out=header+'package repository\n\nimport (\n "context"\n\n "'+module+'/domain/entity"\n)\n'+''.join(t['interface'] for t in ts)
 write(Path('domain/repository')/(dom+'.go'),out)
# Registry bertipe untuk seluruh tabel.
out=header+'package repository\n\nimport (\n "gorm.io/gorm"\n\n domainrepo "'+module+'/domain/repository"\n "'+module+'/repository/pgstore"\n'+''.join(' "'+module+'/repository/'+d+'"\n' for d in sorted(bydomain))+')\n\n// Registry menyatukan dependency persistensi HRM pada satu database.\ntype Registry struct {\n Transactor domainrepo.Transactor\n'+''.join(' '+t['name']+' domainrepo.'+t['name']+'Repository\n' for t in tables)+'}\n\n// New membangun seluruh repository tanpa migrasi atau koneksi lintas management.\nfunc New(db *gorm.DB) (*Registry, error) {\n tx, err := pgstore.NewTransactor(db)\n if err != nil { return nil, err }\n r := &Registry{Transactor:tx}\n'
for t in tables:out+=f' r.{t["name"]}, err = {t["domain"]}.New{t["name"]}Repository(db)\n if err != nil {{ return nil, err }}\n'
out+=' return r,nil\n}\n'
write(Path('repository/registry.go'),out)

from domain_validation import generate, generate_wiring
generate(tables, dbml_tables, sql, enums, write)
generate_wiring(tables, write)

subprocess.run(['gofmt','-w',str(root/'domain/entity'),str(root/'domain/repository'),str(root/'repository')],check=True)
print(f'Generated {len(tables)} repositories, {sum(len(t["filters"]) for t in tables)} typed finders')
