# Kompilasi CHECK DBML ke predicate Go statis; tidak menjalankan atau menafsirkan SQL saat runtime.
import re
from pathlib import Path

class Parser:
    def __init__(self, source):
        self.tokens = re.findall(r"'(?:''|[^'])*'|::|<>|>=|<=|[(),=<>+\-]|[A-Za-z_][A-Za-z_0-9]*|\d+(?:\.\d+)?", source)
        self.pos = 0
        assert ''.join(self.tokens) == re.sub(r'\s+', '', source.replace(' ', '')) or re.sub(r'\s+', '', ''.join(self.tokens)) == re.sub(r'\s+', '', source), source
    def peek(self):
        return self.tokens[self.pos].upper() if self.pos < len(self.tokens) else ''
    def take(self, expected=None):
        value = self.tokens[self.pos]
        if expected: assert value.upper() == expected, (expected, value)
        self.pos += 1
        return value
    def parse(self):
        node = self.disjunction()
        assert self.pos == len(self.tokens), self.tokens[self.pos:]
        return node
    def disjunction(self):
        left = self.conjunction()
        while self.peek() == 'OR':
            self.take();left = ('or',left,self.conjunction())
        return left
    def conjunction(self):
        left = self.comparison()
        while self.peek() == 'AND':
            self.take();left = ('and',left,self.comparison())
        return left
    def comparison(self):
        left = self.sum()
        op = self.peek()
        if op == 'IS':
            self.take();neg = self.peek() == 'NOT'
            if neg: self.take()
            self.take('NULL');return ('notnull' if neg else 'null',left)
        if op in ('IN','NOT'):
            neg = op == 'NOT'
            if neg:self.take()
            self.take('IN');self.take('(');values=[self.sum()]
            while self.peek() == ',':self.take();values.append(self.sum())
            self.take(')');return ('notin' if neg else 'in',left,values)
        if op == 'BETWEEN':
            self.take();low=self.sum();self.take('AND');return ('and',('>=',left,low),('<=',left,self.sum()))
        if op in ('=','<>','>','>=','<','<='):
            self.take();return (op,left,self.sum())
        return left
    def sum(self):
        left=self.primary()
        while self.peek() in ('+','-'):
            op=self.take();left=(op,left,self.primary())
        return left
    def primary(self):
        if self.peek() == '(':
            self.take();node=self.disjunction();self.take(')')
            if self.peek() == '::':
                self.take('::');self.take('DATE')
                assert node[0] == 'utc', node
                return ('utcdate', node[1])
            return node
        token=self.take()
        if token.lower() == 'btrim':
            self.take('(');value=self.primary();self.take(')')
            return ('btrim',value)
        if token.lower() == 'coalesce':
            self.take('(');value=self.primary();self.take(',');fallback=self.primary();self.take(')')
            assert fallback[0]=='text', fallback
            return ('coalesce',value,fallback)
        if self.peek() == 'AT':
            self.take('AT');self.take('TIME');self.take('ZONE');self.take("'UTC'")
            return ('utc',('field',token))
        if token.startswith("'"):return ('text',token[1:-1].replace("''", "'"))
        if token[0].isdigit():return ('number',token)
        return ('field',token)


def generate(tables, bodies, sql, enums, write):
    header='// Code generated by tools/generate_repositories.py; DO NOT EDIT.\n// Validasi field dan CHECK berasal dari baseline/DBML HRM.\npackage entity\n\n'
    enum_code=header
    for raw,values in re.findall(r'CREATE TYPE "(\w+)" AS ENUM \((.*?)\);',sql,re.S):
        typename=enums[raw]
        allowed=', '.join('"'+v+'"' for v in re.findall(r"'([^']+)'",values))
        enum_code+=f'// IsValid memeriksa anggota enum {typename}.\nfunc (v {typename}) IsValid() bool {{ switch v {{ case {allowed}: return true }};return false }}\n'
    write(Path('domain/entity/enums_validation.go'),enum_code)
    grouped={}
    total=0
    for t in tables:
        # Validasi rekrutmen memuat aturan manual dari migrasi aditif.
        if t['domain']=='recruitment':continue
        cols={c['column']:c for c in t['columns']}
        def expr(n):
            if n[0]=='field':
                c=cols[n[1]];return '(*x.'+c['field']+')' if c['type'].startswith('*') else 'x.'+c['field']
            if n[0]=='text':return '"'+n[1]+'"'
            if n[0]=='number':return n[1]
            if n[0]=='btrim':return 'strings.Trim(string('+expr(n[1])+')," ")'
            if n[0]=='utcdate':return expr(n[1])+'.UTC()'
            if n[0]=='coalesce':
                guards=nullable(n[1])
                if not guards:return expr(n[1])
                return 'func() string {if '+' && '.join(sorted(guards))+' {return string('+expr(n[1])+')};return '+expr(n[2])+'}()'
            raise ValueError(n)
        def is_number(n):
            if n[0] in ('number','+','-'):return True
            if n[0]=='field':return cols[n[1]]['sql_type'].lower().startswith(('numeric','integer','bigint','smallint'))
            return False
        def num(n):
            if n[0] in ('+','-'):
                return ('ruleAdd' if n[0]=='+' else 'ruleSubtract')+'('+num(n[1])+','+num(n[2])+')'
            return 'ruleNumber(fmt.Sprint('+expr(n)+'))' if n[0]=='field' else 'ruleNumber("'+n[1]+'")'
        def nullable(n):
            if n[0]=='field':
                c=cols[n[1]]
                return {'x.'+c['field']+' != nil'} if c['type'].startswith('*') else set()
            if n[0] in ('btrim','utcdate'):return nullable(n[1])
            if len(n)==3 and n[0] in ('+','-'):return nullable(n[1])|nullable(n[2])
            return set()
        def boolean(n):
            return n[0] in ('and','or','null','notnull','in','notin','=','<>','>','>=','<','<=')
        def compile(n):
            op=n[0]
            if op in ('and','or'):return ('ruleAnd' if op=='and' else 'ruleOr')+'('+compile(n[1])+','+compile(n[2])+')'
            if op in ('null','notnull'):
                c=cols[n[1][1]];assert c['type'].startswith('*') or c['type'] in ('JSON','[]byte'),n
                return 'ruleKnown(x.'+c['field']+(' == nil)' if op=='null' else ' != nil)')
            if op in ('in','notin'):
                checks=[compile(('=',n[1],v)) for v in n[2]]
                value=checks[0]
                for check in checks[1:]:value='ruleOr('+value+','+check+')'
                return 'ruleNot('+value+')' if op=='notin' else value
            assert op in ('=','<>','>','>=','<','<='),n
            a,b=n[1:]
            if boolean(a) or boolean(b):return 'ruleTruthCompare('+compile(a)+','+compile(b)+',"'+op+'")'
            guards=nullable(a)|nullable(b)
            if is_number(a) or is_number(b):predicate='ruleNumberCompare('+num(a)+','+num(b)+',"'+op+'")'
            elif a[0]=='utcdate':predicate='ruleCompareResult(CompareDates('+expr(a)+','+expr(b)+'),"'+op+'")'
            elif a[0]=='field' and cols[a[1]]['sql_type'] in ('date','timestamptz'):
                predicate='ruleCompareResult('+('CompareDates('+expr(a)+','+expr(b)+')' if cols[a[1]]['sql_type']=='date' else expr(a)+'.Compare('+expr(b)+')')+',"'+op+'")'
            else:
                if any(c[0]=='field' and cols[c[1]]['sql_type']=='uuid' for c in (a,b)):
                    assert op in ('=','<>');predicate=('!' if op=='<>' else '')+'strings.EqualFold('+expr(a)+','+expr(b)+')'
                else:predicate='string('+expr(a)+')'+('==' if op=='=' else '!=' if op=='<>' else op)+'string('+expr(b)+')'
            return 'rulePresent('+ ' && '.join(sorted(guards))+',func()bool{return '+predicate+'})' if guards else 'ruleKnown('+predicate+')'
        name=t['name'];table=t['table']
        out=f'// Validate memeriksa snapshot {table} sebelum dipakai domain.\nfunc (x *{name}) Validate() error {{\n if x==nil {{return hrerrors.Invalid("{table}","must not be nil")}}\n'
        for c in t['columns']:
            field=c['column'];v='x.'+c['field'];typ=c['sql_type'];optional=c['type'].startswith('*')
            value='(*'+v+')' if optional else v
            required=not optional and c['type'] not in ('JSON','[]byte')
            # JSON/bytea nullable disimpulkan dari deklarasi SQL, bukan representasi slice Go.
            declaration=re.search(r'^  "'+field+r'" ([^\n]+)',re.search(r'CREATE TABLE "'+table+r'" \((.*?)\n\);',sql,re.S)[1],re.M)[1]
            required='NOT NULL' in declaration or c['pk']
            check=''
            if typ=='uuid':check=f'ValidateUUID("{field}",{value})'
            elif typ in enums:check=f'validateEnum("{field}",{value}.IsValid())'
            elif typ.startswith(('varchar','char')) or typ=='text':
                length=int(re.search(r'\((\d+)\)',typ)[1]) if '(' in typ else 0
                exact=length if typ.startswith('char(') else 0
                check=f'validateText("{field}",string({value}),{str(required).lower()},{length},{exact})'
            elif typ.startswith('numeric'):
                precision,scale=re.findall(r'\d+',typ);check=f'{value}.ValidatePrecision({precision},{scale})'
            elif typ in ('date','timestamptz'):check=f'validateTime("{field}",{value})'
            elif typ=='jsonb':check=f'validateJSON("{field}",{v},{str(required).lower()})'
            elif typ=='bytea':check=f'validateBytes("{field}",{v},{str(required).lower()})'
            elif typ.lower()=='bigint' and (c['pk'] or field.endswith('_id')):
                check=f'validateIdentity("{field}",{value},{str(c["serial"]).lower()})'
            if check:
                if optional:out+=f' if {v}!=nil {{ if err:={check};err!=nil {{ return hrerrors.Invalid("{field}","has invalid value") }} }}\n'
                else:out+=f' if err:={check};err!=nil {{return hrerrors.Invalid("{field}","has invalid value")}}\n'
        rules=re.findall(r'`([^`]+)` \[name: \'([^\']+)\'\]',bodies[table])
        for source,rule in rules:
            # validateText sudah menolak spasi kosong pada kedua kolom wajib.
            if rule == 'ck_hr_worker_assignment_transfer_input':
                continue
            out+=' if '+compile(Parser(source).parse())+f'==ruleFalse {{return hrerrors.Invalid("{table}","{rule}")}}\n';total+=1
        out+=' return nil\n}\n'
        out+=f'\n// New{name} memvalidasi snapshot tanpa membuat UUID, default bisnis atau grant.\nfunc New{name}(value {name})(*{name},error){{ if err:=value.Validate();err!=nil{{return nil,err}};return &value,nil }}\n'
        out+=f'var _ Validatable=(*{name})(nil)\n'
        grouped.setdefault(t['domain'],[]).append(out)
    for domain,parts in grouped.items():
        body='\n'.join(parts)
        imports='import (\n'
        if 'fmt.' in body:imports+='"fmt"\n'
        if 'strings.' in body:imports+='"strings"\n'
        imports+='\nhrerrors "github.com/integrione/erp-retail/backend/services/human_resource/domain/errors"\n)\n\n'
        write(Path('domain/entity')/(domain+'_validation.go'),header+imports+body)
    print(f'Generated validation for {len(tables)} entities and {total} CHECK constraints')
